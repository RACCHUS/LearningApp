#!/usr/bin/env python3
"""Derive a catalog resource map (data/resource_maps/) from a reviewed
concept mapping (data/concept_mappings/), companion plan v1.0 EX-5.

The concept mapping says, per objective of a target, which sections of an
open textbook hold its content, how closely they match and what they are
for (teach, example, practice). A resource map needs, per objective,
whether the resource covers it and at what depth. This is a fixed,
mechanical translation; nothing is judged here:

  match exact or partial        -> depth teaches   (or practises when the
                                   section's only role is practice)
  match prerequisite            -> depth introduces
  match supplementary           -> depth introduces
  match unrelated               -> dropped
  roles include practice        -> has_practice true, else false
  confidence                    -> copied

An objective with no section left is covered: false. The review block is
not invented: it names the concept mapping's own review, and the map is
approved only when that review is approved.

usage:
  python tool/derive_resource_map.py <concept_mapping.yaml> <resource_id> [--check]

Writes data/resource_maps/<target_slug>__<resource_id>.yaml. With --check,
writes nothing and exits 1 if the file on disk differs (for CI).
"""
from __future__ import annotations

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
CONTENT = ROOT / "content"
MAPS = ROOT / "data" / "resource_maps"

DEPTH = {"exact": "teaches", "partial": "teaches", "prerequisite": "introduces", "supplementary": "introduces"}


def objective_codes(manifest_name: str) -> list[str]:
    manifest = yaml.safe_load((CONTENT / manifest_name).read_text(encoding="utf-8")) or {}
    return [str(o["code"]) for d in manifest.get("domains", []) for o in d.get("objectives", [])]


def derive(mapping_path: Path, resource_id: str) -> tuple[str, dict]:
    src = yaml.safe_load(mapping_path.read_text(encoding="utf-8")) or {}
    slug = src["from"]["target_slug"]
    by_objective: dict[str, list[dict]] = {}
    for entry in src.get("mappings") or []:
        sections = []
        for s in entry.get("sections") or []:
            match = s.get("match")
            if match not in DEPTH:
                continue
            roles = list(s.get("roles") or [])
            depth = "practises" if match in ("exact", "partial") and roles == ["practice"] else DEPTH[match]
            sections.append({
                "label": f"{s['section']} {s['title']}",
                "locator": s.get("locator"),
                "start_seconds": None,
                "end_seconds": None,
                "depth": depth,
                "has_practice": "practice" in roles,
                "confidence": s.get("confidence") or "medium",
            })
        by_objective[str(entry["objective"])] = sections

    review = src.get("review") or {}
    approved = review.get("status") == "approved"
    out_review = {"status": "approved" if approved else "pending"}
    if approved:
        out_review.update({
            "reviewer_kind": review.get("reviewer_kind"),
            "reviewer_model": review.get("reviewer_model"),
            "reviewed_on": review.get("reviewed_on"),
            "notes": (
                f"Not reviewed separately: derived mechanically by tool/derive_resource_map.py from "
                f"data/concept_mappings/{mapping_path.name}, whose review is the one named here."
            ),
        })

    coverage = []
    for code in objective_codes(src["from"]["manifest"]):
        sections = by_objective.get(code, [])
        coverage.append({"objective": code, "covered": bool(sections), "sections": sections})

    doc = {
        "target_slug": slug,
        "resource_id": resource_id,
        "method": (
            f"Derived by tool/derive_resource_map.py from data/concept_mappings/{mapping_path.name} "
            "(section titles and locators from the pinned textbook's table of contents; match and role "
            "per section from that reviewed mapping). Public facts only; nothing copied from the book."
        ),
        "authored_by": src.get("authored_by", "ai-drafted-by-claude"),
        "review": out_review,
        "coverage": coverage,
    }
    header = (
        "# Generated by tool/derive_resource_map.py from "
        f"data/concept_mappings/{mapping_path.name}. Do not edit by hand:\n"
        "# change the concept mapping and regenerate. Validate: python tool/verify_external_resources.py\n"
    )
    return f"{slug}__{resource_id}.yaml", header + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=110)


def main(argv: list[str]) -> int:
    args = [a for a in argv if not a.startswith("--")]
    if len(args) != 2:
        print(__doc__)
        return 2
    name, text = derive(Path(args[0]), args[1])
    target = MAPS / name
    if "--check" in argv:
        current = target.read_text(encoding="utf-8") if target.exists() else ""
        if current.replace("\r\n", "\n") != text:
            print(f"{target.relative_to(ROOT)} is out of date; run tool/derive_resource_map.py")
            return 1
        print(f"{target.relative_to(ROOT)} matches its concept mapping")
        return 0
    target.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {target.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
