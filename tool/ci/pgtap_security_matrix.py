#!/usr/bin/env python3
"""Generate the database security-check matrix from the pgTAP suite (plan §12).

pgTAP assertion counts are not SQL coverage, so the plan asks for a matrix of
*what kind* of security evidence each area has. This script reads every
`supabase/tests/*.sql`, classifies it into a product area, and counts the
signals of security testing it contains:

* planned assertions (`plan(N)`): their sum must match pg_prove's total;
* roles exercised (`set [local] role anon | authenticated | service_role`);
* identity switches (setting the JWT subject; two or more usually means a
  cross-user check);
* denial / absence checks (`throws_ok`, `throws_like`, `ok(not …)`, `is_empty`);
* privilege checks (`has_table/column/schema/function_privilege`);
* RLS-enabled checks (`relrowsecurity`).

The counts are static text signals, not proof: the matrix shows where
evidence exists and where it is thin. Read the test file before relying on a
row.

    python3 tool/ci/pgtap_security_matrix.py --write   # regenerate the doc
    python3 tool/ci/pgtap_security_matrix.py --check   # CI: fail if stale
"""
from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
TESTS_DIR = "supabase/tests"
DOC = "docs/testing/DATABASE_SECURITY_MATRIX.md"

# (area, filename prefixes), first match wins.
AREAS: list[tuple[str, tuple[str, ...]]] = [
    ("Analytics, privacy & retention", ("ana_102", "ana_103")),
    ("Learner progress & events", ("ana_001", "learning_events", "study_progress", "user_xp", "tel_01b",
                                   "item_analytics")),
    ("Assessment, grading & simulation", ("assessment_", "clep_", "exam_", "manifest_", "simulation_")),
    ("Excel / software-learning uploads & storage", ("software_learning",)),
    ("Community, educators & moderation", ("community_", "educator_", "moderation_", "lesson_contribution")),
    ("Content, lessons & import", ("content_", "lesson_", "import_", "library_", "user_curriculum", "word_learning",
                                    "native_literacy")),
    ("Catalog, taxonomy & versioning", ("catalog_", "cip_", "taxonomy_", "learning_target", "target_version",
                                         "version_governance", "versioned_api")),
    ("Feature controls & cost", ("marketing_feature", "cost_")),
    ("Schema integrity", ("schema_drift",)),
]
OTHER = "Other"

_PLAN = re.compile(r"\bplan\s*\(\s*(\d+)\s*\)", re.I)
_NO_PLAN = re.compile(r"\bno_plan\s*\(\s*\)", re.I)
_ROLE = re.compile(r"\bset\s+(?:local\s+)?role\s+(anon|authenticated|service_role)\b", re.I)
_IDENTITY = re.compile(r"request\.jwt\.claim\.sub|\"sub\"\s*:", re.I)
_DENIAL = re.compile(r"\bthrows_ok\b|\bthrows_like\b|\bok\s*\(\s*not\b|\bis_empty\b", re.I)
_PRIVILEGE = re.compile(r"\bhas_(?:table|column|schema|function)_privilege\b", re.I)
_RLS = re.compile(r"\brelrowsecurity\b", re.I)


@dataclass
class FileSignals:
    name: str
    area: str
    planned: int
    no_plan: bool = False
    roles: set[str] = field(default_factory=set)
    identity_switches: int = 0
    denials: int = 0
    privileges: int = 0
    rls_checks: int = 0


def area_of(name: str) -> str:
    for area, prefixes in AREAS:
        if name.startswith(prefixes):
            return area
    return OTHER


def scan(path: Path) -> FileSignals:
    text = re.sub(r"--[^\n]*", "", path.read_text(encoding="utf-8", errors="replace"))  # drop SQL comments
    plans = [int(n) for n in _PLAN.findall(text)]
    return FileSignals(
        name=path.name,
        area=area_of(path.name),
        planned=sum(plans),
        no_plan=bool(_NO_PLAN.search(text)) and not plans,
        roles={r.lower() for r in _ROLE.findall(text)},
        identity_switches=len(_IDENTITY.findall(text)),
        denials=len(_DENIAL.findall(text)),
        privileges=len(_PRIVILEGE.findall(text)),
        rls_checks=len(_RLS.findall(text)),
    )


def _planned(f: FileSignals) -> str:
    return "runtime (`no_plan`)" if f.no_plan else str(f.planned)


def has_security_signal(f: FileSignals) -> bool:
    """Denial, privilege or RLS assertions, or a cross-user identity switch."""
    return bool(f.denials or f.privileges or f.rls_checks or f.identity_switches >= 2)


def _roles(roles: set[str]) -> str:
    order = ["anon", "authenticated", "service_role"]
    return ", ".join(r for r in order if r in roles) or "—"


def render(files: list[FileSignals]) -> str:
    area_names = [a for a, _ in AREAS] + [OTHER]
    by_area = {a: [f for f in files if f.area == a] for a in area_names}
    total_planned = sum(f.planned for f in files)
    lines = [
        "# Database Security-Check Matrix",
        "",
        "<!-- Generated by tool/ci/pgtap_security_matrix.py --write. Do not edit by hand; CI fails if stale. -->",
        "",
        "What kind of security evidence the pgTAP suite (`supabase/tests/`) holds, by product area. "
        "pgTAP runs four times in the required database job (incremental upgrade, hosted-ledger backfill, "
        "clean slate, post-ingestion), and `tool/ci/check_pgtap_parity.py` requires identical totals each time.",
        "",
        "Columns are **static text signals**, not proof. Read a test before relying on its row.",
        "- **Roles**: database roles the tests switch to (`set [local] role …`).",
        "- **Identity switches**: times a test sets the JWT subject; two or more usually means a cross-user check.",
        "- **Denial checks**: `throws_ok`, `throws_like`, `ok(not …)` and `is_empty`, i.e. asserting something is refused or absent.",
        "- **Privilege checks**: `has_table/column/schema/function_privilege` assertions on grants.",
        "- **RLS checks**: assertions that row-level security is enabled (`relrowsecurity`).",
        "- A file has a **security signal** if it has any denial, privilege or RLS check, or at least two identity "
        "switches (cross-user tests often assert that another learner's rows count as zero).",
        "",
        f"**Totals:** {len(files)} test files, {total_planned} planned assertions"
        + (f", plus {sum(f.no_plan for f in files)} files using `no_plan()` (counted only when run; "
           "pg_prove reports the full total in the database job)." if any(f.no_plan for f in files) else "."),
        "",
        "## By area",
        "",
        "| Area | Files | Planned assertions | Files testing `anon` | Files with ≥2 identity switches | Denial checks | Privilege checks | RLS checks |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for area in area_names:
        group = by_area[area]
        if not group:
            continue
        lines.append(
            f"| {area} | {len(group)} | {sum(f.planned for f in group)}"
            f"{' + ' + str(sum(f.no_plan for f in group)) + ' no_plan' if any(f.no_plan for f in group) else ''} | "
            f"{sum('anon' in f.roles for f in group)} | {sum(f.identity_switches >= 2 for f in group)} | "
            f"{sum(f.denials for f in group)} | {sum(f.privileges for f in group)} | {sum(f.rls_checks for f in group)} |"
        )
    thin = [f for f in files if not has_security_signal(f)]
    lines += ["", "## Files with no security signal", ""]
    if thin:
        lines.append("No denial, privilege or RLS check and fewer than two identity switches. These may be "
                     "integrity, performance or contract tests rather than security tests. "
                     "Review whether their area needs a negative-path check.")
        lines.append("")
        lines += [f"- `{f.name}` ({f.area}, {_planned(f)} assertions)" for f in thin]
    else:
        lines.append("None.")
    lines += ["", "## By file", "",
              "| File | Area | Planned | Roles | Identity switches | Denial | Privilege | RLS |",
              "|---|---|---|---|---|---|---|---|"]
    for f in sorted(files, key=lambda f: (area_names.index(f.area), f.name)):
        lines.append(f"| `{f.name}` | {f.area} | {_planned(f)} | {_roles(f.roles)} | {f.identity_switches} | "
                     f"{f.denials} | {f.privileges} | {f.rls_checks} |")
    return "\n".join(lines) + "\n"


def build(root: Path) -> str:
    tests = sorted((root / TESTS_DIR).glob("*.sql"))
    if not tests:
        raise SystemExit(f"error: no pgTAP files in {root / TESTS_DIR}")
    return render([scan(p) for p in tests])


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help=f"regenerate {DOC}")
    mode.add_argument("--check", action="store_true", help=f"fail if {DOC} is stale")
    parser.add_argument("--root", type=Path, default=REPO_ROOT)
    args = parser.parse_args(argv)

    text = build(args.root)
    doc = args.root / DOC
    if args.write:
        doc.parent.mkdir(parents=True, exist_ok=True)
        doc.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {DOC}")
        return 0
    current = doc.read_text(encoding="utf-8").replace("\r\n", "\n") if doc.is_file() else ""
    if current != text:
        print(f"::error file={DOC}::stale database security matrix; run "
              f"`python3 tool/ci/pgtap_security_matrix.py --write` and commit the result")
        return 1
    print(f"{DOC} is up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
