#!/usr/bin/env python3
"""Read-only parity gate: committed College Algebra YAML == generator output.

``content/clep_college_algebra.yaml`` is generated by
``tool/generate_clep_algebra_course.py`` from the authoring modules in
``tool/curriculum_clep_algebra``. This gate proves the committed artifact is
exactly what the authoring source produces, so tests that read the authoring
modules also describe what ships.

What it compares (plan §0A.2 step 5, §0B.1):

* the generator's manifest after a round trip through the generator's own
  YAML dumper and ``yaml.safe_load``, against ``yaml.safe_load`` of the
  committed file;
* type-strictly: mapping key order, quoting and whitespace are ignored, but
  list order, option order, missing/extra keys, values **and types** must match
  (plain ``==`` would accept ``True == 1`` or ``1 == 1.0``);
* determinism: two independent builds in one process must be identical, which
  also catches a build that mutates shared module-level objects.

It never writes to ``content/``. On mismatch it prints only the differing
paths, never values, so answer keys are not echoed into logs.

Exit codes: 0 parity, 1 mismatch or nondeterminism, 2 cannot run.

This gate verifies generator parity, not mathematical truth; that is the job
of tool/tests/test_clep_algebra_math_accuracy.py.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

DEFAULT_COMMITTED = ROOT / "content" / "clep_college_algebra.yaml"
MAX_REPORTED = 25


def strict_diff(a, b, path: str = "$") -> list[str]:
    """Return paths where a and b differ in structure, type or value."""
    if type(a) is not type(b):
        return [f"{path}: type {type(a).__name__} != {type(b).__name__}"]
    if isinstance(a, dict):
        diffs: list[str] = []
        for key in a.keys() - b.keys():
            diffs.append(f"{path}.{key}: only in generated")
        for key in b.keys() - a.keys():
            diffs.append(f"{path}.{key}: only in committed")
        for key in a.keys() & b.keys():
            diffs.extend(strict_diff(a[key], b[key], f"{path}.{key}"))
        return sorted(diffs)
    if isinstance(a, list):
        diffs = []
        if len(a) != len(b):
            diffs.append(f"{path}: length {len(a)} != {len(b)}")
        for i, (x, y) in enumerate(zip(a, b)):
            diffs.extend(strict_diff(x, y, f"{path}[{i}]"))
        return diffs
    return [] if a == b else [f"{path}: value differs"]


def generated_manifest():
    """Build the manifest and normalize it exactly as the generator writes it."""
    import yaml

    from tool.generate_clep_algebra_course import CleanYamlDumper, build_manifest

    manifest = build_manifest()
    text = yaml.dump(
        manifest, Dumper=CleanYamlDumper, default_flow_style=False, sort_keys=False, allow_unicode=True
    )
    return manifest, yaml.safe_load(text)


def check(committed_path: Path) -> list[str]:
    import yaml

    with committed_path.open(encoding="utf-8") as fh:
        committed = yaml.safe_load(fh)

    first_raw, first = generated_manifest()
    second_raw, second = generated_manifest()
    problems = [f"nondeterministic build: {d}" for d in strict_diff(first_raw, second_raw)]
    problems += [f"nondeterministic serialization: {d}" for d in strict_diff(first, second)]
    problems += strict_diff(first, committed)
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="College Algebra generator/committed YAML parity gate.")
    parser.add_argument("--committed", type=Path, default=DEFAULT_COMMITTED)
    args = parser.parse_args(argv)

    try:
        problems = check(args.committed)
    except Exception as exc:  # noqa: BLE001 - any failure to run must fail closed
        print(f"::error::algebra parity gate could not run: {type(exc).__name__}: {exc}")
        return 2

    if problems:
        print(f"::error::{args.committed.name} differs from generator output ({len(problems)} paths).")
        for p in problems[:MAX_REPORTED]:
            print(f"  {p}")
        if len(problems) > MAX_REPORTED:
            print(f"  ... and {len(problems) - MAX_REPORTED} more")
        print("Regenerate with: python3 tool/generate_clep_algebra_course.py (then review the diff).")
        return 1
    print(f"College Algebra parity OK: {args.committed.as_posix()} matches generator output (deterministic).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
