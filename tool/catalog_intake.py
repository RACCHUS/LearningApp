#!/usr/bin/env python3
"""Private destination-candidate intake and evidence-based demand ranking.

No record generated by this tool is a verified license requirement, official
course, or measured popularity claim. Requires explicit --write for DB writes.
Only Python standard library is used; no service key can be passed as CLI arg.

Usage:
    python3 tool/catalog_intake.py validate
    python3 tool/catalog_intake.py rank
    python3 tool/catalog_intake.py import --confirm-project xzvkdwebtbxlrxagtzlv --write
"""
from __future__ import annotations

import argparse
import json
import math
import os
import re
import sys
import urllib.error
import urllib.parse
import urllib.request
from collections import defaultdict
from pathlib import Path

BASE = Path(__file__).resolve().parents[1]
CANDIDATES = BASE / "data/catalog/initial_destination_candidates.json"
SIGNALS = BASE / "data/catalog/demand_signal_observations.json"
PROJECT_REF = "xzvkdwebtbxlrxagtzlv"
ALLOWED_TYPES = {
    "certification", "professional_license", "licensure_exam",
    "standardized_exam", "academic_program", "training_course",
}
METRIC_CATEGORY = {
    "bls_annual_openings": "labor",
    "onet_job_postings": "labor",
    "ipeds_completions": "education",
    "issuer_exam_participants": "education",
    "search_interest_index": "trend",
    "community_goal_saves": "community",
    "community_searches": "community",
}
# Proposed weights. Not a claim that any of these measures have been collected.
CATEGORY_WEIGHT = {"labor": 0.35, "education": 0.25, "trend": 0.20, "community": 0.20}
KEY_PATTERN = re.compile(r"^[a-z0-9_]{3,48}$")
PERIOD_PATTERN = re.compile(r"^20\d{2}(?:-(?:0[1-9]|1[0-2]))?$")


def https(url: object) -> bool:
    if not isinstance(url, str) or any(c.isspace() for c in url):
        return False
    try:
        parsed = urllib.parse.urlparse(url)
        return parsed.scheme == "https" and bool(parsed.netloc) and not parsed.username
    except ValueError:
        return False


def read_data(path: Path) -> dict:
    payload = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(payload, dict) or payload.get("schema_version") != 1:
        raise ValueError(f"{path.name}: expected JSON schema_version=1")
    return payload


def candidate_key(row: dict) -> tuple[str, str]:
    return (row["source_namespace"], row["source_key"])


def validate(catalog: dict, demand: dict) -> dict:
    rows = catalog.get("candidates")
    if not isinstance(rows, list) or not rows:
        raise ValueError("Candidate registry must contain records")
    if catalog.get("candidate_count") != len(rows):
        raise ValueError("Declared candidate_count differs from actual records")
    keys = set()
    for index, r in enumerate(rows):
        if not isinstance(r, dict):
            raise ValueError(f"Candidate #{index}: not an object")
        required = {"source_namespace", "source_key", "destination_type", "title",
                    "issuer_name", "issuer_url", "source_url", "jurisdiction",
                    "review_status", "publication_status", "source_rights", "metadata"}
        if not required <= set(r):
            raise ValueError(f"Candidate #{index}: missing {sorted(required - set(r))}")
        if not KEY_PATTERN.fullmatch(r["source_namespace"]):
            raise ValueError(f"Invalid namespace at record #{index}")
        if not isinstance(r["source_key"], str) or not 1 <= len(r["source_key"]) <= 128:
            raise ValueError(f"Invalid source key at record #{index}")
        key = candidate_key(r)
        if key in keys:
            raise ValueError(f"Duplicate candidate source identity: {key}")
        keys.add(key)
        if r["destination_type"] not in ALLOWED_TYPES:
            raise ValueError(f"Unknown destination type: {key}")
        if not 3 <= len(r["title"].strip()) <= 240 or not 2 <= len(r["issuer_name"].strip()) <= 200:
            raise ValueError(f"Empty/overlong candidate title or issuer: {key}")
        if not https(r["issuer_url"]) or not https(r["source_url"]):
            raise ValueError(f"Non-HTTPS or invalid issuer/source URL: {key}")
        if r["review_status"] != "pending" or r["publication_status"] != "draft":
            raise ValueError(f"Import seed must remain private and unreviewed: {key}")
        if r["source_rights"] != "link_metadata_only":
            raise ValueError(f"Seed cannot assert approved reuse rights: {key}")
        if not isinstance(r["metadata"], dict) or r["metadata"].get("popularity_measured") is not False:
            raise ValueError(f"Candidate must explicitly disclaim measured popularity: {key}")
        if r.get("cip_code") is not None and not re.fullmatch(r"\d{2}\.\d{4}", r["cip_code"]):
            raise ValueError(f"Invalid CIP code for {key}")
        if not isinstance(r["jurisdiction"], str) or not 2 <= len(r["jurisdiction"]) <= 48:
            raise ValueError(f"Invalid jurisdiction: {key}")

    observations = demand.get("signals")
    if not isinstance(observations, list):
        raise ValueError("Demand file must contain a signals array")
    observed_ids = set()
    for index, r in enumerate(observations):
        key = (r.get("source_namespace"), r.get("source_key"))
        if key not in keys:
            raise ValueError(f"Demand observation #{index} refers to an unknown candidate")
        metric = r.get("metric")
        if metric not in METRIC_CATEGORY:
            raise ValueError(f"Demand observation #{index} uses an unsupported metric")
        v = r.get("metric_value")
        if isinstance(v, bool) or not isinstance(v, (int, float)) or not math.isfinite(v) or v < 0:
            raise ValueError(f"Demand observation #{index} must have finite nonnegative value")
        if not PERIOD_PATTERN.fullmatch(str(r.get("observed_period", ""))):
            raise ValueError(f"Demand observation #{index} has invalid observed period")
        if not https(r.get("evidence_url")):
            raise ValueError(f"Demand observation #{index} has invalid source URL")
        if not r.get("publisher") or not r.get("method_note") or not r.get("geography"):
            raise ValueError(f"Demand observation #{index} lacks provenance")
        if r.get("data_rights") not in {"metadata_only", "approved_aggregate"}:
            raise ValueError(f"Demand observation #{index} has unreviewed rights")
        identity = (key, metric, r["observed_period"], r["geography"], r["publisher"])
        if identity in observed_ids:
            raise ValueError(f"Duplicate observation: {identity}")
        observed_ids.add(identity)
    return {"candidates": len(rows), "observations": len(observations),
            "types": {k: sum(r["destination_type"] == k for r in rows) for k in sorted(ALLOWED_TYPES)}}


def score_candidates(catalog: dict, demand: dict) -> list[dict]:
    """Comparable within metric+geography+period only, never across incompatible units.

    Require >=2 independent signal categories to call any rank measured.
    No observations means no fake 0 scores and no rankings.
    """
    records = demand["signals"]
    groups = defaultdict(list)
    for row in records:
        groups[(row["metric"], row["geography"], row["observed_period"])].append(row)
    normalized = defaultdict(lambda: defaultdict(list))
    for group in groups.values():
        # Relative comparison is meaningless with only one observation.
        if len(group) < 2:
            continue
        ceiling = max(math.log1p(r["metric_value"]) for r in group)
        if ceiling <= 0:
            continue
        for row in group:
            identity = (row["source_namespace"], row["source_key"])
            cat = METRIC_CATEGORY[row["metric"]]
            normalized[identity][cat].append(math.log1p(row["metric_value"]) / ceiling)
    result = []
    for row in catalog["candidates"]:
        scores = normalized.get(candidate_key(row), {})
        if len(scores) < 2:
            continue
        used_weights = sum(CATEGORY_WEIGHT[c] for c in scores)
        score = sum(CATEGORY_WEIGHT[c] * (sum(v) / len(v))
                    for c, v in scores.items()) / used_weights
        result.append({
            "source_namespace": row["source_namespace"],
            "source_key": row["source_key"],
            "title": row["title"],
            "score": round(score, 5),
            "evidence_categories": sorted(scores),
            "coverage": round(used_weights, 2),
            "score_status": "observed_partial",
        })
    return sorted(result, key=lambda r: (-r["score"], r["title"]))


def rest_post(url: str, key: str, table: str, batch: list[dict]) -> None:
    params = urllib.parse.urlencode({"on_conflict": "source_namespace,source_key"})
    request = urllib.request.Request(
        f"{url.rstrip('/')}/rest/v1/{table}?{params}",
        data=json.dumps(batch).encode("utf-8"),
        method="POST",
        headers={
            "apikey": key,
            "Content-Type": "application/json",
            "Prefer": "resolution=ignore-duplicates,return=minimal",
            "User-Agent": "LearningApp-CatalogIntake/1.0",
        },
    )
    try:
        with urllib.request.urlopen(request, timeout=60) as response:
            if response.status not in (200, 201, 204):
                raise RuntimeError(f"Catalog intake HTTP {response.status}")
    except urllib.error.HTTPError as error:
        # Never print server echo of secret keys, identifiers or raw records.
        raise RuntimeError(f"Catalog intake HTTP {error.code}; no success claimed") from error


def import_candidates(catalog: dict, confirmed_project: str) -> None:
    if confirmed_project != PROJECT_REF:
        raise ValueError("Refusing import to any project other than Learning App")
    url = os.getenv("SUPABASE_URL", "").rstrip("/")
    expected = f"https://{PROJECT_REF}.supabase.co"
    if url != expected:
        raise ValueError("SUPABASE_URL does not match the intended Learning App project")
    key = os.getenv("SUPABASE_SERVICE_ROLE_KEY", "").strip()
    if not key.startswith("sb_secret_"):
        raise ValueError("A modern sb_secret_ admin key is required in the environment")
    if len(key) < 20:
        raise ValueError("Admin key appears incomplete")
    # Deliberately never send workflow-specific review/publication flags,
    # nor re-upsert existing identities: duplicates must retain prior reviews.
    allowed = {
        "source_namespace", "source_key", "destination_type", "title",
        "issuer_name", "issuer_url", "source_url", "jurisdiction",
        "cip_code", "onet_code", "edition", "metadata",
    }
    prepared = [{k: v for k, v in row.items() if k in allowed}
                for row in catalog["candidates"]]
    for start in range(0, len(prepared), 50):
        rest_post(url, key, "catalog_intake_candidates", prepared[start:start + 50])
    print(json.dumps({"result": "submitted_to_private_review_queue",
                      "attempted": len(prepared),
                      "publication": "none",
                      "note": "Duplicate source identities skipped; existing approvals not overwritten."}))


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("operation", choices=("validate", "rank", "import"))
    p.add_argument("--write", action="store_true",
                   help="Required for import; this performs live database writes")
    p.add_argument("--confirm-project", default="", help="Expected Supabase project ref")
    args = p.parse_args()
    catalog = read_data(CANDIDATES)
    demand = read_data(SIGNALS)
    summary = validate(catalog, demand)
    if args.operation == "validate":
        print(json.dumps({"status": "valid_private_intake", **summary}, indent=2))
    elif args.operation == "rank":
        ranked = score_candidates(catalog, demand)
        print(json.dumps({"status": "measured_ranking" if ranked else "insufficient_evidence",
                          "ranked_count": len(ranked),
                          "candidate_count": summary["candidates"],
                          "notice": "A candidate without qualifying measured signals is unranked, not unpopular.",
                          "ranked": ranked}, indent=2))
    elif not args.write:
        raise ValueError("Import is disabled by default. Set --write and --confirm-project explicitly")
    else:
        import_candidates(catalog, args.confirm_project)
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (ValueError, RuntimeError, urllib.error.URLError) as error:
        print(f"Catalog intake rejected: {error}", file=sys.stderr)
        sys.exit(2)
